    [Fact]
    public void NR17702_CliRejectsCompleteMcapWithLateGeometryEventsAndOrderOmitted()
    {
        var directory = Directory.CreateDirectory(Path.Combine(Path.GetTempPath(),
            $"duck177-late-order-{Guid.NewGuid():N}")).FullName;
        try
        {
            var path = Path.Combine(directory, "actual-late-with-both-events-removed.mcap");
            var bytes = Convert.FromBase64String(ReviewFixtureBase64);
            Assert.Equal(ReviewFixtureSha256, Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant());
            File.WriteAllBytes(path, bytes);

            // This is a complete MCAP with valid structural CRC, not a truncated partial.
            _ = new McapReaderFactory(path).Validate();
            using var output = new StringWriter();
            using var error = new StringWriter();
            int? exitCode = null;
            var failure = Record.Exception(() =>
            {
                exitCode = CaptureReplayCommand.Run(["--capture", path], output, error);
            });

            Assert.True(failure is InvalidDataException || (failure is null && exitCode != 0),
                $"Incomplete late-input recording accepted: exit={exitCode}, output={output}, error={error}, failure={failure}");
        }
        finally
        {
            Directory.Delete(directory, recursive: true);
        }
    }

